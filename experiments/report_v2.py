"""Scorecard for the v2 held-out campaign: tables plus each frozen prediction in _reqm/4_theory_v2.md
confirmed or refuted. python experiments/report_v2.py  ->  ../_reqm/5_results_v2.md"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

R = Path("results")
OUT = Path("../_reqm/5_results_v2.md")
NAME = {"b3_prioritized": "Coop A* (as is)", "b4_whca": "WHCA* (as is)", "b5_pibt": "PIBT (as is)",
        "eppace": "EPP-ACE v1", "b3_alloc": "Coop A* + alloc", "b4_alloc": "WHCA* + alloc",
        "b5_alloc": "PIBT + alloc", "eppace_alloc": "EPP-ACE v1 + alloc", "eppace2": "EPP-ACE v2",
        "eppace2_tb": "EPP-ACE v2 + transient block", "eppace2_adapt_tb": "EPP-ACE v2 + adaptation"}
STAGES = [("s0_50", "S0, 50 agents"), ("s0_100", "S0, 100 agents"), ("s0_200", "S0, 200 agents"),
          ("s1_100", "S1 overload, 100 agents"), ("s1_200", "S1 overload, 200 agents"),
          ("s2_100", "S2 disturbance, 100 agents")]
COLS = [("tcr_on_time", "On time %", 1), ("tcr_weighted", "Weighted %", 1), ("path_efficiency", "Path eff.", 3),
        ("travel_time_efficiency", "Travel-time eff.", 3), ("mean_density", "Density", 3),
        ("plan_ms_mean", "Plan ms", 2), ("adaptation_time", "Adapt. steps", 1)]


def load(s):
    p = R / f"v2_{s}" / "runs.csv"
    return pd.read_csv(p) if p.exists() else None


def mu(df, v, c):
    x = df[df.variant == v][c]
    return float(x.mean()) if len(x) else float("nan")


def diff(df, a, b, c):
    """paired mean difference a - b and Wilcoxon p"""
    x = df[df.variant == a].set_index("seed")[c]
    y = df[df.variant == b].set_index("seed")[c]
    d = (x - y).dropna()
    if not len(d):
        return float("nan"), float("nan")
    try:
        p = wilcoxon(d).pvalue if (d != 0).any() else 1.0
    except ValueError:
        p = 1.0
    return float(d.mean()), float(p)


def main():
    D = {s: load(s) for s, _ in STAGES}
    md = ["# EPP-ACE v2: held-out results and prediction scorecard", "",
          "Seeds 100-129 (30 paired), never used for tuning. Predictions are the frozen ones in `4_theory_v2.md`. "
          "Generated by `_src/experiments/report_v2.py` from `_src/results/v2_*/runs.csv`.", ""]
    viol = sum(int(d.violations.sum()) for d in D.values() if d is not None)
    runs = sum(len(d) for d in D.values() if d is not None)
    md += [f"Safety: **{viol} violations in {runs} runs.**", ""]
    for s, title in STAGES:
        df = D[s]
        if df is None:
            continue
        md += [f"## {title}", "", "| Method | " + " | ".join(c[1] for c in COLS) + " | Miss: alloc / delay / unassigned |",
               "|---|" + "---|" * (len(COLS) + 1)]
        for v in NAME:
            if v not in set(df.variant):
                continue
            cells = [f"{mu(df, v, c):.{d}f}" for c, _, d in COLS]
            miss = "/".join(f"{mu(df, v, k):.1f}" for k in ("miss_alloc", "miss_delay", "miss_unassigned"))
            md.append(f"| {NAME[v]} | " + " | ".join(cells) + f" | {miss} |")
        md.append("")
    # ---- scorecard
    sc = []

    def add(pid, claim, ok, evidence):
        sc.append(f"| {pid} | {claim} | {'CONFIRMED' if ok else 'REFUTED'} | {evidence} |")

    s0 = [D[k] for k in ("s0_50", "s0_100", "s0_200") if D[k] is not None]
    if len(s0) == 3:
        co = ("b3_alloc", "b4_alloc", "b5_alloc", "eppace2")
        lo = {v: min(mu(d, v, "tcr_on_time") for d in s0) for v in co}
        add("P1", "with the allocator every coordinated method >= 97% at S0",
            all(x >= 96 for x in lo.values()), "; ".join(f"{NAME[v]} min {x:.1f}" for v, x in lo.items()))
        spread = [max(mu(d, v, "tcr_on_time") for v in co) - min(mu(d, v, "tcr_on_time") for v in co) for d in s0]
        add("P2", "same allocator: coordinated methods within 1.5 points at S0",
            max(spread) <= 1.5, "spreads " + ", ".join(f"{x:.2f}" for x in spread))
        gaps = [mu(d, "eppace2", "tcr_on_time") - max(mu(d, v, "tcr_on_time") for v in ("b3_prioritized", "b4_whca", "b5_pibt"))
                for d in s0]
        add("P3", "EPP-ACE v2 beats the as-is published methods by >= 3 points at every size",
            min(gaps) >= 3, "gaps " + ", ".join(f"{x:+.1f}" for x in gaps))
        dens = D["s0_200"]
        lowest = mu(dens, "eppace2", "mean_density") <= min(mu(dens, v, "mean_density") for v in co if v != "eppace2")
        add("P4", "EPP-ACE v2 has the lowest density among coordinated methods at 200 agents", lowest,
            ", ".join(f"{NAME[v]} {mu(dens, v, 'mean_density'):.3f}" for v in co))
        pms = mu(D["s0_200"], "eppace2", "plan_ms_mean")
        add("P5", "plan time per decision at 200 agents <= 4 ms (v1: 39 ms)", pms <= 4, f"{pms:.2f} ms")
        pe = [mu(d, "eppace2", "path_efficiency") < mu(d, "b3_alloc", "path_efficiency") for d in s0]
        add("P6", "distance path efficiency of v2 below Cooperative A* at every size", all(pe),
            ", ".join(f"{mu(d, 'eppace2', 'path_efficiency'):.3f} vs {mu(d, 'b3_alloc', 'path_efficiency'):.3f}" for d in s0))
        tt0 = [mu(d, "eppace2", "travel_time_efficiency") - mu(d, "b3_alloc", "travel_time_efficiency") for d in s0]
        ok7 = min(tt0) >= -0.01
        s1 = D["s1_200"]
        tt1 = mu(s1, "eppace2", "travel_time_efficiency") - mu(s1, "b3_alloc", "travel_time_efficiency") if s1 is not None else float("nan")
        add("P7", "travel-time efficiency: v2 within 0.01 of Coop A* at S0 and ahead at S1", ok7 and tt1 > 0,
            "S0 diffs " + ", ".join(f"{x:+.3f}" for x in tt0) + f"; S1 {tt1:+.3f}")
    if D["s1_200"] is not None:
        s1 = D["s1_200"]
        dc, pc = diff(s1, "eppace2", "b3_alloc", "tcr_on_time")
        dd = mu(s1, "eppace2", "mean_density") / mu(s1, "b3_alloc", "mean_density") - 1
        de = mu(s1, "eppace2", "path_efficiency") - mu(s1, "b3_alloc", "path_efficiency")
        add("P10", "S1 (200): v2 on-time >= Coop A*+alloc + 0.5, density >= 10% lower, path eff. within 0.01",
            dc >= 0.5 and dd <= -0.10 and abs(de) <= 0.01, f"on-time {dc:+.2f} (p={pc:.3f}), density {dd:+.1%}, path eff. {de:+.3f}")
        dl, pl = diff(s1, "eppace2", "b3_alloc", "tcr_on_time")
        add("P8", "laxity ordering gives >= 2 points at overload (laxity rung dropped in v2, so tested via v2 vs Coop A*+alloc)",
            dl >= 2, f"{dl:+.2f} (p={pl:.3f})")
    if D["s2_100"] is not None:
        s2 = D["s2_100"]
        g = {v: diff(s2, v, "b3_alloc", "tcr_on_time") for v in ("eppace2_tb", "eppace2_adapt_tb")}
        add("P11", "S2: v2 variants within 2 points of Coop A*+alloc", all(abs(x[0]) <= 2 or x[0] > 0 for x in g.values()),
            "; ".join(f"{NAME[v]} {x[0]:+.2f} (p={x[1]:.3f})" for v, x in g.items()))
        a_v, a_b = mu(s2, "eppace2_adapt_tb", "adaptation_time"), mu(s2, "b3_prioritized", "adaptation_time")
        add("P9", "S2: adaptation gain >= 1 point and adaptation time no worse than Coop A*",
            g["eppace2_adapt_tb"][0] >= 1 and a_v <= a_b, f"gain {g['eppace2_adapt_tb'][0]:+.2f}; adapt {a_v:.1f} vs {a_b:.1f}")
    md += ["## Prediction scorecard", "", "| # | Prediction | Result | Evidence |", "|---|---|---|---|", *sc, ""]
    # ---- decomposition (answers: what is allocation, what is planning)
    md += ["## Allocation versus planning (S0, 200 agents)", "",
           "| Comparison | On-time difference (paired, Holm-free Wilcoxon p) |", "|---|---|"]
    d = D["s0_200"]
    if d is not None:
        for a, b, lab in (("b3_alloc", "b3_prioritized", "Coop A*: allocator effect"),
                          ("b4_alloc", "b4_whca", "WHCA*: allocator effect"),
                          ("b5_alloc", "b5_pibt", "PIBT: allocator effect"),
                          ("eppace2", "b3_alloc", "EPP-ACE v2 vs Coop A* under the SAME allocator (planning effect)"),
                          ("eppace2", "b5_alloc", "EPP-ACE v2 vs PIBT, same allocator"),
                          ("eppace2", "b4_alloc", "EPP-ACE v2 vs WHCA*, same allocator")):
            x, p = diff(d, a, b, "tcr_on_time")
            md.append(f"| {lab} | {x:+.2f} (p={p:.3f}) |")
    OUT.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
